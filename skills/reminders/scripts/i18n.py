CATALOG = {"en": EN, "it": IT}


def t(lang: str, msg: str, **kw) -> str:
    """Message for `msg` in `lang`, falling back to English, then to the key.

    The parameter is named `msg` (not `key`) because some catalog entries
    themselves take a `{key}` placeholder.
    """
    table = CATALOG.get(lang) or {}
    text = table.get(msg)
    if text is None:
        text = EN.get(msg, msg)
    if kw:
        try:
            return text.format(**kw)
        except (KeyError, IndexError):
            return text
    return text
